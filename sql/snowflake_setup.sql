-- Run once as ACCOUNTADMIN. Everything is restricted to this learning database.
USE ROLE ACCOUNTADMIN;
CREATE WAREHOUSE IF NOT EXISTS ELT_WH
    WAREHOUSE_SIZE = 'XSMALL' AUTO_SUSPEND = 60 AUTO_RESUME = TRUE
    INITIALLY_SUSPENDED = TRUE;
CREATE DATABASE IF NOT EXISTS RETAIL_DEMO;
CREATE SCHEMA IF NOT EXISTS RETAIL_DEMO.RAW;
CREATE SCHEMA IF NOT EXISTS RETAIL_DEMO.STAGING;
CREATE SCHEMA IF NOT EXISTS RETAIL_DEMO.MARTS;

-- The application can work only in the demo database; it never uses ACCOUNTADMIN.
CREATE ROLE IF NOT EXISTS ELT_ROLE;
GRANT USAGE ON WAREHOUSE ELT_WH TO ROLE ELT_ROLE;
GRANT USAGE ON DATABASE RETAIL_DEMO TO ROLE ELT_ROLE;
GRANT USAGE ON ALL SCHEMAS IN DATABASE RETAIL_DEMO TO ROLE ELT_ROLE;
GRANT CREATE TABLE, CREATE STAGE, CREATE FILE FORMAT ON SCHEMA RETAIL_DEMO.RAW TO ROLE ELT_ROLE;
GRANT CREATE TABLE, CREATE VIEW ON SCHEMA RETAIL_DEMO.STAGING TO ROLE ELT_ROLE;
GRANT CREATE TABLE, CREATE VIEW ON SCHEMA RETAIL_DEMO.MARTS TO ROLE ELT_ROLE;

-- The generator replaces the public-key placeholder. Private keys stay local.
CREATE USER IF NOT EXISTS ELT_SERVICE TYPE=SERVICE
    DEFAULT_ROLE=ELT_ROLE DEFAULT_WAREHOUSE=ELT_WH;
ALTER USER ELT_SERVICE SET RSA_PUBLIC_KEY='__PUBLIC_KEY__';
GRANT ROLE ELT_ROLE TO USER ELT_SERVICE;
GRANT ROLE ELT_ROLE TO ROLE SYSADMIN;

USE ROLE ELT_ROLE;
CREATE TABLE IF NOT EXISTS RETAIL_DEMO.RAW.ORDERS (
    TRANSACTION_ID NUMBER(38,0) NOT NULL,
    ORDERED_AT TIMESTAMP_NTZ NOT NULL,
    STORE VARCHAR, PRODUCT VARCHAR, CATEGORY VARCHAR,
    QUANTITY NUMBER(38,0), UNIT_PRICE NUMBER(12,2), DISCOUNT_PCT NUMBER(38,0),
    SOURCE VARCHAR, LOADED_AT TIMESTAMP_NTZ NOT NULL
);

-- Power BI uses a read-only role and your normal interactive login.
USE ROLE ACCOUNTADMIN;
CREATE ROLE IF NOT EXISTS RETAIL_REPORTER;
GRANT USAGE ON WAREHOUSE ELT_WH TO ROLE RETAIL_REPORTER;
GRANT USAGE ON DATABASE RETAIL_DEMO TO ROLE RETAIL_REPORTER;
GRANT USAGE ON SCHEMA RETAIL_DEMO.MARTS TO ROLE RETAIL_REPORTER;
GRANT SELECT ON ALL TABLES IN SCHEMA RETAIL_DEMO.MARTS TO ROLE RETAIL_REPORTER;
GRANT SELECT ON FUTURE TABLES IN SCHEMA RETAIL_DEMO.MARTS TO ROLE RETAIL_REPORTER;
GRANT SELECT ON ALL VIEWS IN SCHEMA RETAIL_DEMO.MARTS TO ROLE RETAIL_REPORTER;
GRANT SELECT ON FUTURE VIEWS IN SCHEMA RETAIL_DEMO.MARTS TO ROLE RETAIL_REPORTER;
GRANT ROLE RETAIL_REPORTER TO USER "__REPORT_USER__";
-- The same local demo key can authenticate Power BI with a read-only active role.
-- ELT_SERVICE already has these table privileges through ELT_ROLE.
GRANT ROLE RETAIL_REPORTER TO USER ELT_SERVICE;
GRANT ROLE RETAIL_REPORTER TO ROLE SYSADMIN;
SELECT 'Demo resources ready' AS STATUS;
